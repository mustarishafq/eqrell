/**
 * Pick a random quote from the bank.
 * Uses a stable seed within the same session to avoid flicker during rerenders.
 */
export const pickRandomQuote = (seed) => {
  if (FAMILY_QUOTES.length === 0) return null
  const s = typeof seed === 'number' ? seed : Math.floor(Math.random() * 1e6)
  return FAMILY_QUOTES[s % FAMILY_QUOTES.length]
}
